-- LINE 綁定的建立時間。
--
-- 用途是交接：看得出哪些綁定是上一屆留下來的，也能盤點「很久沒動靜」的帳號。
-- 沒有這個欄位的話，管理清單只知道「有人綁著」，卻分不出新舊。
--
-- ⚠️ 刻意「不」回填既有綁定的時間。
--
-- 現有那幾筆的實際綁定時間無從得知，填 CURRENT_TIMESTAMP 等於捏造資料——
-- 而這個欄位存在的目的正是「判斷這筆是不是上一屆留下來的」，
-- 填了假值會讓它反過來誤導人：所有舊綁定看起來都像今天剛建立的。
-- NULL 是誠實的答案，畫面上顯示為「未知」。

ALTER TABLE users ADD COLUMN line_bound_at DATETIME;
