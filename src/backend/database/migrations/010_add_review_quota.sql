-- 課程評價的回饋金名額（quota）。
--
-- 規則：每門課（同課號、同教授、同學年期）只有前 N 篇評價具備回饋金資格，
-- 系上必修 3、系上選修 2、其他 1。投稿本身永遠不受限制，額滿只代表沒有回饋金。
--
-- 純 ADD COLUMN 加一次性 UPDATE，沒有 DROP、不動任何既有欄位的語意，
-- 舊版程式碼在新資料庫上仍可正常運作（多出來的欄位它不會讀）。

-- ---------------------------------------------------------------------------
-- 1) 課程分類。由 scripts/fetchNtuCourses.js 從 NOL 抓取後寫入。
--
-- requirement: 'required' | 'elective' | NULL
-- is_im_target: 授課對象是否為資管系／資管所
--
-- ⚠️ NULL 代表「還沒被新版爬蟲抓過」，一律落到「其他」（1 名）。
-- 絕對不可以被解讀成系上必修——這是本遷移最重要的一條不變式。
-- 判定邏輯集中在 config/reviewQuota.js 的 resolveTier()，有單元測試守著。
--
-- 這也表示：只跑 migration 而沒重跑 npm run fetch-courses 的話，
-- 每一門課都會顯示「其他 1 名」。部署順序必須是 migrate → fetch-courses → 驗證 → 前端。
-- ---------------------------------------------------------------------------
ALTER TABLE course_catalog ADD COLUMN requirement VARCHAR(10);
ALTER TABLE course_catalog ADD COLUMN is_im_target BOOLEAN;

-- ---------------------------------------------------------------------------
-- 2) 名額規則生效前就存在的評價一律豁免。
--
-- 這些人投稿的當下，畫面上根本沒有名額資訊，事後套用等於溯及既往。
-- 沒有這一步的話，上線當天會有一批已經核准、甚至已經口頭答應要發的評價
-- 瞬間變成不可發放——這是本功能最可能在正式環境炸掉的地方。
--
-- 這個旗標只在這裡寫入一次，應用程式碼永遠不會再更新它。
-- 它是「不可變的輸入」而不是「推導出來的結論」，所以不會像 is_paid 那樣漂移。
-- （對照組：PATCH /:id/status 拒絕已發放的評價時不會清 is_paid，那就是衍生狀態漂移。）
--
-- 註：這個 UPDATE 會觸發 update_course_reviews_timestamp，把所有既有評價的
-- updated_at 一起推到現在。目前沒有任何畫面在用這個欄位，可以接受。
-- ---------------------------------------------------------------------------
ALTER TABLE course_reviews ADD COLUMN quota_exempt BOOLEAN NOT NULL DEFAULT 0;
UPDATE course_reviews SET quota_exempt = 1;

-- ---------------------------------------------------------------------------
-- 3) 被拒絕後修改重送時的「重新排隊時間」。
--
-- PUT /:id 會把 status 打回 pending 但不會動 created_at。沒有這一欄的話：
--   1/1  A 投稿
--   1/3  A 被拒絕（名額釋出）
--   1/6  B 投稿，1/7 核准，等待發放
--   1/10 A 修改後重送 → A 以 1/1 的時間插到隊伍最前面
-- 結果是已經被告知「已核准」的 B 因為第三者的編輯而失去回饋金資格。
--
-- 只有 rejected → pending 這一條路徑會寫入它；單純編輯已核准的評價不算重新排隊。
-- 保持 NULL 時排序完全等同於用 created_at，是安全的退化行為。
-- ---------------------------------------------------------------------------
ALTER TABLE course_reviews ADD COLUMN requeued_at DATETIME;

